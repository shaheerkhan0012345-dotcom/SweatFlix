/**
 * 100% Crash-Proof Source Resolver for expo-image.
 * Guarantees expo-image never encounters `{ uri: undefined }` or `{ uri: number }`
 * which causes the fatal `undefined is not a function` error at Image.tsx (330:84).
 */
export function resolveSafeImageSource(image: any, fallbackUrl: string = DEFAULT_FALLBACK_URL): any {
  if (image === null || image === undefined) {
    return { uri: fallbackUrl };
  }
  // Metro require asset ID number
  if (typeof image === 'number') {
    return image;
  }
  // String URL
  if (typeof image === 'string') {
    const trimmed = image.trim();
    if (trimmed.length > 0) {
      return { uri: trimmed };
    }
    return { uri: fallbackUrl };
  }
  // Object: safe extraction
  if (typeof image === 'object') {
    if (typeof image.uri === 'string' && image.uri.trim().length > 0) {
      return { uri: image.uri.trim() };
    }
    if (typeof image.uri === 'number') {
      return image.uri;
    }
    if (typeof image.default === 'number') {
      return image.default;
    }
    if (typeof image.default === 'string' && image.default.trim().length > 0) {
      return { uri: image.default.trim() };
    }
  }
  return { uri: fallbackUrl };
}

